/**
 * Seeds all application collections directly into Firestore if empty or forced.
 */
export async function seedFirestoreDatabase(force = false): Promise<{ seeded: boolean; message: string }> {
  try {
    const usersSnap = await getDocs(collection(db, 'users'));
    if (!force && usersSnap.size > 0) {
      return { seeded: false, message: `Database already contains ${usersSnap.size} users.` };
    }

    console.log('--- Starting Firestore Database Seeding ---');

    // 1. Seed Users
    for (const user of INITIAL_FIRESTORE_USERS) {
      await setDoc(doc(db, 'users', user.id), user);
    }
    console.log(`Seeded ${INITIAL_FIRESTORE_USERS.length} users into Firestore.`);

    // 2. Seed Availability Slots
    for (const slot of INITIAL_FIRESTORE_SLOTS) {
      await setDoc(doc(db, 'slots', slot.id), slot);
    }
    console.log(`Seeded ${INITIAL_FIRESTORE_SLOTS.length} availability slots into Firestore.`);

    // 3. Seed Appointments
    for (const apt of INITIAL_FIRESTORE_APPOINTMENTS) {
      await setDoc(doc(db, 'appointments', apt.id), apt);
    }
    console.log(`Seeded ${INITIAL_FIRESTORE_APPOINTMENTS.length} appointments into Firestore.`);

    // 4. Seed Medical Records
    for (const rec of INITIAL_FIRESTORE_MEDICAL_RECORDS) {
      await setDoc(doc(db, 'medicalRecords', rec.id), rec);
    }
    console.log(`Seeded ${INITIAL_FIRESTORE_MEDICAL_RECORDS.length} medical records into Firestore.`);

    // 5. Seed Psychological Records (Prontuários CFP / LGPD)
    for (const pront of INITIAL_FIRESTORE_PSYCHOLOGICAL_RECORDS) {
      await setDoc(doc(db, 'psychologicalRecords', pront.id), pront);
    }
    console.log(`Seeded ${INITIAL_FIRESTORE_PSYCHOLOGICAL_RECORDS.length} psychological records into Firestore.`);

    // 6. Seed Chat Messages
    for (const msg of INITIAL_FIRESTORE_MESSAGES) {
      await setDoc(doc(db, 'messages', msg.id), msg);
    }
    console.log(`Seeded ${INITIAL_FIRESTORE_MESSAGES.length} messages into Firestore.`);

    return { seeded: true, message: 'All collections successfully populated in Firestore database.' };
  } catch (err: any) {
    console.error('Error seeding Firestore database:', err);
    throw err;
  }
}
